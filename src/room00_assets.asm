.code
upload_room00_patterns:
        lda #<(CHR_GAME*16)
        sta <_di+0
        lda #>(CHR_GAME*16)
        sta <_di+1
        call vdc_di_to_mawr
        tia room00_patterns,VDC_DL,256
        rts

