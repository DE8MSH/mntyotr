assert used_types == set(TYPE_DATA), "generator contains missing or unreferenced late Decor types"

for typ, (ew, eh, ecols) in EXPECTED_TYPES.items():
    w, h, bmp_hex, cols_hex = TYPE_DATA[typ]
    assert (w, h) == (ew, eh), f"type ${typ:02X} dimensions {(w,h)} != {(ew,eh)}"
    assert cols_hex.lower() == ecols.lower(), f"type ${typ:02X} colour stream drift"
